/*
 * lapid.h: C API of lapid, fast ML inference on any device (CPU, CUDA, Vulkan, Metal).
 *
 * Engine level (like ggml.h): devices, .lapid model files, lazy tensors, one function per
 * tensor op, eval. Models, tokenizers and sampling stay in Rust.
 *
 * CONVENTIONS
 *   - Every fallible function returns lapid_status: LAPID_OK (0) or a LAPID_ERR_* code.
 *     Details are a JSON string from lapid_last_error() on the same thread:
 *     {"status": 2, "error": "shape_mismatch", "message": "..."}.
 *   - Results come back through out parameters (last arguments). On error, out
 *     parameters are left untouched.
 *   - Integer codes (LAPID_DTYPE_*, LAPID_UNARY_*, ...) are plain int32_t; unknown codes
 *     are rejected with LAPID_ERR_INVALID_ARGUMENT.
 *   - Axes are int64_t; negative values count from the end (-1 = last axis).
 *   - Ops are lazy: they build a graph node. Work happens in lapid_eval / lapid_to_host_*.
 *
 * OWNERSHIP
 *   - lapid_device, lapid_file and lapid_tensor are opaque, refcounted handles. Every
 *     handle returned through an out parameter holds one reference that the caller
 *     releases with lapid_*_free (NULL is accepted). lapid_*_retain adds a reference;
 *     the pointer value is unchanged.
 *   - Input handles and buffers are borrowed for the duration of the call only. Data
 *     passed to lapid_tensor_from_data / lapid_file_open_bytes is copied.
 *   - Tensors keep their inputs (and the file image they came from) alive internally, so
 *     handles can be freed in any order.
 *   - char* / void* returned through out parameters (JSON, dumps) are released with
 *     lapid_free. const char* results (version, names) and lapid_last_error() are owned by
 *     the library; never free them. Blob pointers live as long as their file handle.
 *
 * THREAD SAFETY
 *   - All functions may be called from any thread. Handles are immutable and may be
 *     shared and used concurrently across threads (including free/retain).
 *   - lapid_eval on the same device from several threads is safe.
 *   - The last error is per thread. The log callback is process-wide and may be invoked
 *     from any thread that calls into lapid.
 *
 * SAFETY
 *   - Pointers must be valid for the documented sizes; NULL is rejected with
 *     LAPID_ERR_INVALID_ARGUMENT where a value is required. Passing freed handles or
 *     handles from another allocation is undefined behavior.
 *   - Panics inside lapid are caught and reported as LAPID_ERR_PANIC.
 *
 * VERSIONING
 *   Call lapid_check_abi(LAPID_ABI_VERSION) once at startup.
 */

