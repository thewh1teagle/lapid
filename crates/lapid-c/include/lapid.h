lapid_status lapid_softmax(const lapid_tensor *x, lapid_tensor **out);

// Layer norm over the last axis: `(x - mean) / sqrt(var + eps) * weight + bias`
// (`weight`, `bias` `[D]`).
lapid_status lapid_layer_norm(const lapid_tensor *x,
                              const lapid_tensor *weight,
                              const lapid_tensor *bias,
                              float eps,
                              lapid_tensor **out);

// RMS norm over the last axis: `x * rsqrt(mean(x^2) + eps) * weight` (`weight` `[D]`).
lapid_status lapid_rms_norm(const lapid_tensor *x,
                            const lapid_tensor *weight,
                            float eps,
                            lapid_tensor **out);

// Scaled dot-product attention: q `[B, H, Sq, D]`, k / v `[B, H, Sk, D]` (same float
// dtype), optional additive f32 `mask` broadcastable to `[B, H, Sq, Sk]` (NULL for none).
// `causal`: query i attends key j iff j <= i + (Sk - Sq). Output `[B, H, Sq, D]`.
lapid_status lapid_attention(const lapid_tensor *q,
                             const lapid_tensor *k,
                             const lapid_tensor *v,
                             const lapid_tensor *mask,
                             float scale,
                             bool causal,
                             lapid_tensor **out);

// Mixture-of-experts matmul (ggml MUL_MAT_ID): x `[T, K]` (float), experts `w` `[E, N, K]`
// (float or quantized, each in matmul_t form), `ids` i32 `[T, R]` -> `[T, R, N]` with
// `out[t, r] = w[ids[t, r]] @ x[t]`. Out-of-range ids fail at eval.
lapid_status lapid_matmul_id(const lapid_tensor *x,
                             const lapid_tensor *w,
                             const lapid_tensor *ids,
                             lapid_tensor **out);

// Gated delta rule (ggml GATED_DELTA_NET): q, k `[B, T, H, Dk]`, v `[B, T, H, Dv]`, g (log
// decay) and beta `[B, T, H]`, state `[B, H, Dk, Dv]`, all f32. Returns `[B, H, T + Dk, Dv]`:
// rows `[0, T)` are the outputs, rows `[T, T + Dk)` the final state.
lapid_status lapid_gated_delta_net(const lapid_tensor *q,
                                   const lapid_tensor *k,
                                   const lapid_tensor *v,
                                   const lapid_tensor *g,
                                   const lapid_tensor *beta,
                                   const lapid_tensor *state,
                                   float scale,
                                   lapid_tensor **out);

// A host tensor holding a copy of the data at `data`: row-major, contiguous, in `dtype`
// (for quantized dtypes, the lapid-quant storage layout). The byte count is implied by
// `shape[0..rank]` and `dtype`; the caller may free `data` when this returns.
// `rank == 0` makes a scalar (`shape` may then be NULL).
lapid_status lapid_tensor_from_data(const void *data,
                                    const size_t *shape,
                                    size_t rank,
                                    lapid_dtype dtype,
                                    lapid_tensor **out);

// A constant tensor: `value` broadcast to `shape` in `dtype` (no memory until used).
lapid_status lapid_tensor_full(double value,
                               const size_t *shape,
                               size_t rank,
                               lapid_dtype dtype,
                               lapid_tensor **out);

// `lapid_tensor_full` with value 0.
lapid_status lapid_tensor_zeros(const size_t *shape,
                                size_t rank,
                                lapid_dtype dtype,
                                lapid_tensor **out);

// Add a reference to a tensor handle (the same pointer stays valid until every reference
// is released with `lapid_tensor_free`).
void lapid_tensor_retain(lapid_tensor *t);

// Drop one reference. NULL is a no-op. Graph nodes built from this tensor keep what they
// need alive, so inputs can be freed right after use.
void lapid_tensor_free(lapid_tensor *t);

// Number of dimensions.
lapid_status lapid_tensor_rank(const lapid_tensor *t, size_t *out);

// Copy the shape into `dims[0..cap]` and the rank into `*rank` (`rank` may be NULL).
// `LAPID_ERR_INVALID_ARGUMENT` if `cap` is smaller than the rank (`*rank` is still set).
lapid_status lapid_tensor_shape(const lapid_tensor *t, size_t *dims, size_t cap, size_t *rank);

// Element type code (`LAPID_DTYPE_*`).
lapid_status lapid_tensor_dtype(const lapid_tensor *t, lapid_dtype *out);

// Number of elements (product of the shape; 1 for scalars).
lapid_status lapid_tensor_numel(const lapid_tensor *t, size_t *out);

// Storage size in bytes (quantized dtypes: the full block layout).
lapid_status lapid_tensor_nbytes(const lapid_tensor *t, size_t *out);

// True when the tensor is realized on a device (a result of `lapid_eval` / `lapid_upload`),
// false for host data, constants and unevaluated graph nodes.
lapid_status lapid_tensor_is_realized(const lapid_tensor *t, bool *out);

// The same node with a debug name attached (shows up in schedule dumps).
lapid_status lapid_tensor_named(const lapid_tensor *t, const char *name, lapid_tensor **out);

// Static name of a dtype code ("f32", "f16", "bf16", "i32", "int8", "int4", "q4_k", "q5_k",
// "q6_k"), or NULL for an unknown code. Never free it.
const char *lapid_dtype_name(lapid_dtype dtype);

// Parse a dtype name (as returned by `lapid_dtype_name`) into `*out`.
lapid_status lapid_dtype_from_name(const char *name, lapid_dtype *out);

// Bytes needed to store a tensor of `shape[0..rank]` in `dtype` (for
// `lapid_tensor_from_data` buffers; quantized dtypes include block padding).
lapid_status lapid_dtype_storage_bytes(lapid_dtype dtype,
                                       const size_t *shape,
                                       size_t rank,
                                       size_t *out);

